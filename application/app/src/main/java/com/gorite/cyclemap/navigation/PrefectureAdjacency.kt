/** 全県をキーに持つ隣接表。北海道と沖縄県は道路接続がないため空集合。 */
internal val PREFECTURE_ADJACENCY: Map<String, Set<String>> = buildMap {
    PREFECTURE_ADJACENCY_EDGES.forEach { (a, b) ->
        put(a, get(a).orEmpty() + b)
        put(b, get(b).orEmpty() + a)
    }
    putIfAbsent("北海道", emptySet())
    putIfAbsent("沖縄県", emptySet())
}
